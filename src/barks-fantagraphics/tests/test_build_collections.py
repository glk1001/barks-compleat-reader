"""Guard the pre-baked collection pages in the "All Covers" and "All One-Pagers" overrides.

Each collection is served to the reader as ordinary "extra" pages of its nominal
volume (FANTA_02 for the covers, FANTA_01 for the one-pagers), numbered from the
collection's page base (500) upward: one page per *located* member, in the
collection's own order. The pages are pre-baked (encrypted) into the volume's
override archive by the offline staging and build flow, so these tests pin them
down: the override zip must contain *exactly* the contiguous pages
``500 .. 500+N-1`` as ``.jpg`` entries, where ``N`` is the number of located members.

Unlike the rest of the suite, this reads the real (machine-local) reader override
archives under ``FANTA_VOLUME_OVERRIDES_ROOT``. Locally a missing archive is a hard
failure (it guards against the baked pages drifting); on CI, where this
machine-local data legitimately does not exist, the tests are skipped instead.
The covers may also not have been staged and baked yet: an override with *no*
covers pages skips, where the one-pager collection (no longer regenerated by any
script) must be there.
"""

from __future__ import annotations

import os
import zipfile
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

import pytest
from barks_fantagraphics.barks_covers import COVER_COLLECTION_PAGE_BASE, get_located_covers
from barks_fantagraphics.comic_book_info import (
    COVER_COLLECTION_VOLUME,
    ONE_PAGER_COLLECTION_PAGE_BASE,
    ONE_PAGER_COLLECTION_VOLUME,
    get_located_one_pagers,
)
from barks_fantagraphics.comics_consts import FANTA_VOLUME_OVERRIDES_ROOT
from barks_fantagraphics.fanta_comics_info import FANTA_OVERRIDE_ZIPS

if TYPE_CHECKING:
    from collections.abc import Callable, Sequence

JPG_EXT = ".jpg"
# The stored image bytes are Fernet ciphertext, which always begins with this.
FERNET_TOKEN_PREFIX = b"gAAAA"


@dataclass(frozen=True)
class Collection:
    """One pre-baked collection: where its pages live and what they are made from."""

    name: str
    volume: int  # the nominal volume, whose override holds the pages as extras
    page_base: int
    located: Callable[[], Sequence[object]]
    nothing_located: str  # the failure when there is nothing to bake
    skip_while_unbaked: bool  # an override with no collection pages is expected, for now

    def override_zip_path(self) -> Path:
        return FANTA_VOLUME_OVERRIDES_ROOT / FANTA_OVERRIDE_ZIPS[self.volume]

    def expected_arcnames(self) -> list[str]:
        """Return the contiguous ``<page>.jpg`` names, one per located member."""
        return [f"{self.page_base + i:03d}{JPG_EXT}" for i in range(len(self.located()))]


COLLECTIONS = [
    Collection(
        name="All Covers",
        volume=COVER_COLLECTION_VOLUME,
        page_base=COVER_COLLECTION_PAGE_BASE,
        located=get_located_covers,
        nothing_located="No located covers (COVER_LOCATIONS is empty).",
        skip_while_unbaked=True,
    ),
    Collection(
        name="All One-Pagers",
        volume=ONE_PAGER_COLLECTION_VOLUME,
        page_base=ONE_PAGER_COLLECTION_PAGE_BASE,
        located=get_located_one_pagers,
        nothing_located="No located one-pagers (ONE_PAGER_LOCATIONS all _TODO).",
        skip_while_unbaked=False,
    ),
]


def _page_num(arcname: str) -> int | None:
    stem = Path(arcname).stem
    return int(stem) if stem.isdigit() else None


@pytest.fixture(scope="module", params=COLLECTIONS, ids=[c.name for c in COLLECTIONS])
def collection(request: pytest.FixtureRequest) -> Collection:
    return request.param


@pytest.fixture(scope="module")
def override_zip_path(collection: Collection) -> Path:
    """Path to the collection's real override archive.

    Hard-fails if absent locally; skips on CI, where the archive does not exist.
    """
    zip_path = collection.override_zip_path()
    if not zip_path.is_file():
        msg = f'"{collection.name}" override archive is missing: "{zip_path}".'
        if os.environ.get("CI"):
            pytest.skip(msg)
        pytest.fail(msg)
    return zip_path


@pytest.fixture(scope="module")
def collection_names(collection: Collection, override_zip_path: Path) -> list[str]:
    """Override entries belonging to the collection (page >= base)."""
    with zipfile.ZipFile(override_zip_path, "r") as zf:
        names = [
            name
            for name in zf.namelist()
            if (page := _page_num(name)) is not None and page >= collection.page_base
        ]
    if not names and collection.skip_while_unbaked:
        pytest.skip(f'"{collection.name}" not yet baked into "{override_zip_path.name}".')
    return names


class TestCollectionPages:
    def test_located_members_present(self, collection: Collection) -> None:
        # The collection (and so these tests) is meaningless with nothing to bake.
        assert collection.located(), collection.nothing_located

    def test_collection_pages_match_located_members_exactly(
        self, collection: Collection, collection_names: list[str]
    ) -> None:
        # Exactly the contiguous pages 500..500+N-1 as .jpg: no missing pages, no stale
        # extras, and no wrong extension (a stray 5xx.png would not match the .jpg name).
        assert sorted(collection_names) == sorted(collection.expected_arcnames())

    def test_collection_pages_are_nonempty_encrypted_images(
        self, override_zip_path: Path, collection_names: list[str]
    ) -> None:
        with zipfile.ZipFile(override_zip_path, "r") as zf:
            for arcname in collection_names:
                data = zf.read(arcname)
                assert data.startswith(FERNET_TOKEN_PREFIX), (
                    f'Collection page "{arcname}" is not an encrypted image payload.'
                )
